#!/usr/bin/env python3
"""Generate Shaders/a4k_<v>.hlsl and A4kModels.g.cs from the vendored Anime4K mpv GLSL files.

    python tools/a4k_gen.py

Reads  third_party/Anime4K/Anime4K_Upscale_CNN_x2_{S,M,L}.glsl  (MIT, bloc97; see third_party/Anime4K/README.md)
Writes Shaders/a4k_s.hlsl, a4k_m.hlsl, a4k_l.hlsl (ASCII only) and A4kModels.g.cs (the pass/texture wiring).

The GLSL passes are  conv (3x3 or 1x1, CReLU on the inputs)  ...  depth-to-space + residual onto the bilinear base.
GLSL mat4(v0..v15) is column-major:  out_i = sum_j v[4j+i] * in_j.   HLSL mul(row_vector, float4x4(v0..v15)) is the
same sum, so the 16 numbers are copied verbatim.
"""
import re, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "third_party", "Anime4K")
OUT_SH = os.path.join(ROOT, "Shaders")


def parse(path):
    text = open(path, encoding="utf-8").read()
    blocks = re.split(r"(?m)^//!DESC ", text)[1:]
    passes = []
    for b in blocks:
        desc = b.split("\n", 1)[0]
        binds = re.findall(r"(?m)^//!BIND (\w+)", b)
        save = re.search(r"(?m)^//!SAVE (\w+)", b).group(1)
        # define go_k / g_k : (texture, mode) mode 0 raw, +1 max(x,0), -1 max(-x,0)
        defs = {}
        for m in re.finditer(r"(?m)^#define (go|g)_(\d+)(?:\(x_off, y_off\))? \((.*)\)$", b):
            body = m.group(3)
            mm = re.fullmatch(r"max\((-?)\((\w+?)_texOff\(vec2\(x_off, y_off\)\)\), 0\.0\)", body)                 or re.fullmatch(r"max\((-?)\((\w+?)_tex\(\w+_pos\)\), 0\.0\)", body)
            if mm:
                defs[(m.group(1), int(m.group(2)))] = (mm.group(2), -1 if mm.group(1) == "-" else 1)
                continue
            mm = re.fullmatch(r"(\w+?)_texOff\(vec2\(x_off, y_off\)\)", body)
            if mm:
                defs[(m.group(1), int(m.group(2)))] = (mm.group(1), 0)
                continue
            raise SystemExit("unparsed define: " + m.group(0))
        terms = []
        bias = None
        for m in re.finditer(r"(?m)^\s*(?:vec4 )?result \+?= (mat4|vec4)\(([^)]*)\)(?: \* (go|g)_(\d+)(?:\(([-\d.]+), ([-\d.]+)\))?)?;", b):
            nums = [float(x) for x in m.group(2).split(",")]
            if m.group(1) == "vec4":
                assert len(nums) == 4 and bias is None
                bias = [x.strip() for x in m.group(2).split(",")]
            else:
                assert len(nums) == 16
                tex, mode = defs[(m.group(3), int(m.group(4)))]
                dx = float(m.group(5)) if m.group(5) else 0.0
                dy = float(m.group(6)) if m.group(6) else 0.0
                # keep the original literal text
                lits = [s.strip() for s in m.group(2).split(",")]
                terms.append((tex, mode, int(dx), int(dy), lits))
        kind = "d2s" if "Depth-to-Space" in desc else "conv"
        passes.append(dict(desc=desc, binds=binds, save=save, terms=terms, bias=bias, kind=kind, text=b))
    return passes


def lit(s):
    # GLSL literal -> HLSL float literal (all GLSL ones are valid already; make "0.0"-style explicit)
    if re.fullmatch(r"-?\d+", s):
        s += ".0"
    return s


def mat(lits):
    return "float4x4(" + ", ".join(lit(x) for x in lits) + ")"


def emit_conv_body(p, slot, ind="    "):
    """Statements computing float4 r at integer position q (variable q, dimension dim)."""
    lines = []
    b = p["bias"] or ["0", "0", "0", "0"]
    lines.append(f"{ind}float4 r = float4({', '.join(lit(x) for x in b)});")
    # group by (tex, dx, dy): one load, both CReLU halves
    groups = {}
    order = []
    for tex, mode, dx, dy, lits in p["terms"]:
        k = (tex, dx, dy)
        if k not in groups:
            groups[k] = {}
            order.append(k)
        groups[k][mode] = lits
    for i, k in enumerate(order):
        tex, dx, dy = k
        g = groups[k]
        lines.append(f"{ind}{{ float4 v = LD({slot[tex]}, q, {dx}, {dy});")
        if 0 in g:
            lines.append(f"{ind}  r += mul(v, {mat(g[0])});")
        if 1 in g:
            lines.append(f"{ind}  r += mul(max(v, 0.0), {mat(g[1])});")
        if -1 in g:
            lines.append(f"{ind}  r += mul(max(-v, 0.0), {mat(g[-1])});")
        lines.append(f"{ind}}}")
    return lines


HEAD = """// GENERATED by tools/a4k_gen.py from third_party/Anime4K/{src} - do not edit.
// Anime4K (c) 2019-2021 bloc97, MIT License (third_party/Anime4K/LICENSE). Weights are copied verbatim.
// Port of the mpv GLSL hook passes: conv layers with CReLU inputs (edge pixels clamp), then depth-to-space
// plus residual onto the bilinear-upscaled base.
cbuffer A4k : register(b0)
{{
    int4 dim;     // x,y: size of the convolution textures (= size of the source)
}};
Texture2D<float4> t0 : register(t0);
Texture2D<float4> t1 : register(t1);
Texture2D<float4> t2 : register(t2);
Texture2D<float4> t3 : register(t3);
Texture2D<float4> t4 : register(t4);
Texture2D<float4> t5 : register(t5);
Texture2D<float4> t6 : register(t6);
Texture2D<float4> t7 : register(t7);
Texture2D<float4> t8 : register(t8);
Texture2D<float4> t9 : register(t9);
Texture2D<float4> t10 : register(t10);
Texture2D<float4> t11 : register(t11);
Texture2D<float4> t12 : register(t12);
Texture2D<float4> t13 : register(t13);
Texture2D<float4> t14 : register(t14);
Texture2D<float4> t15 : register(t15);
SamplerState lin : register(s0);

// texel at q + (dx, dy), edge pixels repeated
#define LD(tx, q, dx, dy) tx.Load(int3(clamp((q) + int2(dx, dy), int2(0, 0), dim.xy - 1), 0))
"""


def generate(letter):
    src = f"Anime4K_Upscale_CNN_x2_{letter}.glsl"
    return emit_upscale(parse(os.path.join(SRC, src)), src, os.path.join(OUT_SH, f"a4k_{letter.lower()}.hlsl"))


def emit_upscale(passes, src, out_path, user=False):
    """HLSL of an Anime4K x2 network given as parsed passes (parse() output, or the same structure with other weights).
    user=True: the weights are a user-trained model (header says so); `src` is then a free-text label."""
    head = HEAD.format(src=src)
    if user:
        head = head.replace("from third_party/Anime4K/" + src + " - do not edit.", "(" + src + ") by tools/train_upscaler.py - do not edit.")
        head = head.replace("Anime4K (c) 2019-2021 bloc97, MIT License (third_party/Anime4K/LICENSE). Weights are copied verbatim.",
                            "Network layout (c) 2019-2021 bloc97 (Anime4K, MIT); the weights are the user's own training result.")
    out = [head]
    tex_index = {"MAIN": -1}   # GLSL name -> intermediate texture index (-1 source)
    n_tex = 0
    model = []                 # (entry, [input indices], output index or -2 for final)
    # decide fusion: last conv (1x1, single output) feeding the d2s
    convs = [p for p in passes if p["kind"] == "conv"]
    d2s = [p for p in passes if p["kind"] == "d2s"][0]
    last = convs[-1]
    fuse = all(dx == 0 and dy == 0 for _, _, dx, dy, _ in last["terms"]) and d2s["binds"] == ["MAIN", last["save"]]
    for i, p in enumerate(convs):
        if fuse and p is last:
            continue
        tex_index[p["save"]] = n_tex
        n_tex += 1
    for i, p in enumerate(convs):
        if fuse and p is last:
            continue
        slot = {name: f"t{k}" for k, name in enumerate(p["binds"])}
        entry = f"l{i}"
        out.append(f"\n// {p['desc']}")
        out.append(f"float4 {entry}(float4 sv : SV_Position) : SV_Target")
        out.append("{")
        out.append("    int2 q = int2(sv.xy);")
        out += emit_conv_body(p, slot)
        out.append("    return r;")
        out.append("}")
        model.append((entry, [tex_index[b] for b in p["binds"]], tex_index[p["save"]]))
    # depth to space
    out.append(f"\n// {d2s['desc']}" + (" (fused with the last 1x1 convolution)" if fuse else ""))
    out.append("float4 d2s(float4 sv : SV_Position) : SV_Target")
    out.append("{")
    out.append("    int2 o = int2(sv.xy);")
    out.append("    int2 q = o >> 1;")
    out.append("    int comp = (o.y & 1) * 2 + (o.x & 1);")
    out.append("    float4 base = t0.SampleLevel(lin, (float2(o) + 0.5) / float2(dim.xy * 2), 0);")
    if fuse:
        # t0 = MAIN, then the last conv's own inputs
        slot = {name: f"t{k + 1}" for k, name in enumerate(last["binds"])}
        out += emit_conv_body(last, slot)
        out.append("    float c = r[comp];")
        out.append("    return float4(base.rgb + c, 1.0);")
        model.append(("d2s", [-1] + [tex_index[b] for b in last["binds"]], -2))
    else:
        outs = [b for b in d2s["binds"] if b != "MAIN"]
        for k, name in enumerate(outs):
            out.append(f"    float c{k} = t{k + 1}.Load(int3(q, 0))[comp];")
        if len(outs) == 1:
            out.append("    return float4(base.rgb + c0, 1.0);")
        else:
            assert len(outs) == 3
            out.append("    return float4(base.rgb + float3(c0, c1, c2), 1.0);")
        model.append(("d2s", [-1] + [tex_index[b] for b in outs], -2))
    out.append("}")
    text = "\n".join(out) + "\n"
    text.encode("ascii")
    with open(out_path, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    return model, n_tex


def generate_restore(letter):
    """Anime4K Restore CNN: the same conv layers, but the last pass (3x3 or 1x1 over the layers) adds its 3 outputs to the
    source picture (return result + MAIN_tex(MAIN_pos)) and writes a picture of the SAME size: there is no depth-to-space."""
    src = f"Anime4K_Restore_CNN_{letter}.glsl"
    passes = parse(os.path.join(SRC, src))
    head = HEAD.format(src=src).replace("then depth-to-space\n// plus residual onto the bilinear-upscaled base.", "then the last layer's result\n// is added to the source picture (same size, no scaling).")
    out = [head]
    tex_index = {"MAIN": -1}
    n_tex = 0
    model = []
    for p in passes[:-1]:
        tex_index[p["save"]] = n_tex
        n_tex += 1
    for i, p in enumerate(passes):
        final = p is passes[-1]
        assert p["kind"] == "conv" and (p["save"] == "MAIN") == final
        slot = {name: f"t{k}" for k, name in enumerate(p["binds"])}
        entry = "fin" if final else f"l{i}"
        out.append(f"\n// {p['desc']}" + (" (+ the source picture)" if final else ""))
        out.append(f"float4 {entry}(float4 sv : SV_Position) : SV_Target")
        out.append("{")
        out.append("    int2 q = int2(sv.xy);")
        out += emit_conv_body(p, slot)
        if final:
            assert p["binds"][0] == "MAIN"
            out.append("    return float4(r.rgb + t0.Load(int3(q, 0)).rgb, 1.0);")
            model.append((entry, [tex_index[b] for b in p["binds"]], -2))
        else:
            out.append("    return r;")
            model.append((entry, [tex_index[b] for b in p["binds"]], tex_index[p["save"]]))
        out.append("}")
    text = "\n".join(out) + "\n"
    text.encode("ascii")
    with open(os.path.join(OUT_SH, f"a4k_restore_{letter.lower()}.hlsl"), "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    return model, n_tex


def main():
    cs = ["// GENERATED by tools/a4k_gen.py - do not edit.",
          "// Wiring of the Anime4K CNN passes: for each pass its entry point (Shaders/a4k_<v>.hlsl), the shader-resource inputs",
          "// (-1 = the source picture, k = intermediate texture k) and the intermediate texture it writes (-2 = the final x2 picture).",
          "namespace YuCap;", "",
          "internal static partial class A4kModels", "{"]
    for letter in "SML":
        model, n = generate(letter)
        cs.append(f"    internal static readonly A4kPassInfo[] Passes{letter} =")
        cs.append("    {")
        for entry, ins, o in model:
            cs.append(f"        new(\"{entry}\", new[] {{ {', '.join(str(i) for i in ins)} }}, {o}),")
        cs.append("    };")
        cs.append(f"    internal const int Textures{letter} = {n};")
    for letter in "SML":
        model, n = generate_restore(letter)
        cs.append(f"    internal static readonly A4kPassInfo[] RestorePasses{letter} =")
        cs.append("    {")
        for entry, ins, o in model:
            cs.append(f"        new(\"{entry}\", new[] {{ {', '.join(str(i) for i in ins)} }}, {o}),")
        cs.append("    };")
        cs.append(f"    internal const int RestoreTextures{letter} = {n};")
    cs.append("}")
    with open(os.path.join(ROOT, "A4kModels.g.cs"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(cs) + "\n")


if __name__ == "__main__":
    main()
